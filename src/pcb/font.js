const ADV = 5.4; // cell advance in font units
export const textWidth = (str, h) => (Math.max(1, [...String(str)].length) * ADV - 1.4) * (h / 6);

/**
 * Text → line segments. `h` is the cap height in mm. `x,y` is the anchor (centre of the text block).
 * `rot` in degrees, `mirror` flips horizontally (text on the bottom silkscreen).
 */
export function strokeText(str, { x = 0, y = 0, h = 1, rot = 0, mirror = false } = {}) {
  const chars = [...String(str).toUpperCase()];
  const s = h / 6;
  const total = (chars.length * ADV - 1.4) * s;
  const out = [];
  const a = (rot * Math.PI) / 180, ca = Math.cos(a), sa = Math.sin(a);
  const place = (u, v, cx) => {
    let lx = cx + u * s - total / 2;
    const ly = v * s - h / 2;
    if (mirror) lx = -lx;
    return { x: x + lx * ca - ly * sa, y: y + lx * sa + ly * ca };
  };
  chars.forEach((ch, i) => {
    const glyph = G[ch] ?? (ch === ' ' ? [] : G['#']);
    for (const stroke of glyph) {
      for (let k = 0; k + 3 < stroke.length; k += 2) {
        const p = place(stroke[k], stroke[k + 1], i * ADV * s);
        const q = place(stroke[k + 2], stroke[k + 3], i * ADV * s);
        out.push({ x1: p.x, y1: p.y, x2: q.x, y2: q.y });
      }
      if (stroke.length === 4 && stroke[0] === stroke[2] && stroke[1] === stroke[3]) {
        const p = place(stroke[0], stroke[1], i * ADV * s);
        out.push({ x1: p.x, y1: p.y, x2: p.x + 0.001, y2: p.y });
      }
    }
  });
  return out;
}
